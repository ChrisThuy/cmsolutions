/*
  Generates the static agent index on /oil-gas and /agent-map.

    npm run agent-index

  Both pages are consoles: every agent is drawn by JavaScript from a data
  file. That is right for the interactive map and wrong for everything else.
  Three groups get nothing from it —

    · a crawler on first pass, which sees a couple of hundred characters of
      chrome and concludes the page is empty (our own audit tool reported
      exactly that for both pages);
    · anyone with JavaScript off or broken;
    · the skip link at the top of each page, "Skip the map, list every agent",
      which pointed at a tab that does not exist until JavaScript has run.

  So the list it promises is generated here into the served HTML, between
  markers, and the skip link now points at it. It is real visible content, not
  a hidden block for crawlers: the same list a person would want if they did
  not fancy clicking through a radial map to find out what the thing does.

  Generated, not hand-written, so it cannot drift from the data. The two data
  files share a schema, so one generator serves both — /agent-map's agents
  carry no KPI field, which is why that line is conditional.
*/

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createContext, runInContext } from "node:vm";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const START = "<!-- AGENT-INDEX:START — generated by scripts/build-agent-index.mjs; do not edit by hand -->";
const END = "<!-- AGENT-INDEX:END -->";

const TARGETS = [
  { data: "og-agents-data.js", page: "oil-gas.html", arrangement: "where the work sits in the value chain" },
  { data: "agents-data.js", page: "agent-map.html", arrangement: "where the work sits in the company" },
];

/* The data files are plain scripts that declare consts, so they have nothing
   to import. Run each one and lift the bindings out rather than parsing it. */
function loadData(file) {
  const context = createContext({});
  const source = readFileSync(resolve(root, file), "utf8");
  runInContext(`${source}\n;this.__data = { DEPTS, BRANCHES, AGENTS };`, context);
  return context.__data;
}

const escape = (value) =>
  String(value ?? "").replace(/[&<>"']/g, (c) =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c],
  );

/*
  The "replaces" field is written to stand alone ("Two days of cost build-up"),
  so dropping it after "Replaces " produces "Replaces Two days of cost
  build-up." Lower the first letter — unless the first word is an acronym like
  HSE or HAZOP, which must keep its case.
*/
function lowerFirst(text) {
  const [first = ""] = String(text).split(/\s/);
  if (first.length > 1 && first === first.toUpperCase()) return text;
  return text.charAt(0).toLowerCase() + text.slice(1);
}

function buildIndex({ DEPTS, BRANCHES, AGENTS }, arrangement) {
  const parts = [
    START,
    `<section class="agent-index" id="agent-index" aria-labelledby="agent-index-h">`,
    `  <h2 id="agent-index-h">Every playbook, in full</h2>`,
    `  <p class="agent-index-lede">`,
    `    ${AGENTS.length} prompts across ${DEPTS.length} departments. Each one covers a job a`,
    `    competent person does today, and each is a prompt you copy into your own`,
    `    model — nothing on this page runs by itself. The map above is the same list,`,
    `    arranged by ${arrangement}.`,
    `  </p>`,
  ];

  for (const dept of DEPTS) {
    const branches = BRANCHES.filter((b) => b.d === dept.i);
    const inDept = AGENTS.filter((a) => branches.some((b) => b.i === a.b));
    if (!inDept.length) continue;

    parts.push(
      `  <div class="ai-dept">`,
      `    <h3>${escape(dept.n)} <span class="ai-count">${inDept.length} agents</span></h3>`,
      `    <p class="ai-dept-d">${escape(dept.d)}</p>`,
    );

    for (const branch of branches) {
      const agents = AGENTS.filter((a) => a.b === branch.i);
      if (!agents.length) continue;

      parts.push(
        `    <h4>${escape(branch.n)}</h4>`,
        `    <p class="ai-branch-d">${escape(branch.d2)}</p>`,
        `    <ul>`,
      );

      for (const agent of agents) {
        // What it replaces and the KPI it moves are the two things a reader
        // actually wants; the full brief lives in the console.
        const bits = [];
        if (agent.r) bits.push(`Replaces ${escape(lowerFirst(agent.r))}.`);
        if (agent.kpi) bits.push(`Moves <em>${escape(agent.kpi)}</em>.`);
        parts.push(
          `      <li><b>${escape(agent.n)}</b> — ${bits.join(" ") || "See the console for the full brief."}</li>`,
        );
      }

      parts.push(`    </ul>`);
    }

    parts.push(`  </div>`);
  }

  parts.push(`</section>`, END);
  return parts.join("\n");
}

/*
  --check regenerates and compares instead of writing. Run in the test suite,
  because the failure mode here is silent: someone edits a data file, the
  console picks the change up immediately, and the served HTML keeps claiming
  the old agent count to every crawler and every reader without JavaScript.
*/
const checkOnly = process.argv.includes("--check");
let stale = 0;

for (const target of TARGETS) {
  const data = loadData(target.data);
  const block = buildIndex(data, target.arrangement);

  const file = resolve(root, target.page);
  const page = readFileSync(file, "utf8");
  const from = page.indexOf(START);
  const to = page.indexOf(END);

  if (from === -1 || to === -1) {
    console.error(`  FAIL  ${target.page} — index markers missing`);
    process.exit(1);
  }

  const current = page.slice(from, to + END.length);
  const words = block.replace(/<[^>]+>/g, " ").split(/\s+/).filter(Boolean).length;
  const summary = `${data.AGENTS.length} agents, ${data.DEPTS.length} departments, ~${words} words`;

  if (checkOnly) {
    if (current === block) {
      console.log(`  PASS  ${target.page.padEnd(16)} index matches the data (${summary})`);
    } else {
      stale++;
      console.error(`  FAIL  ${target.page.padEnd(16)} index is stale — run: npm run agent-index`);
    }
    continue;
  }

  writeFileSync(file, page.slice(0, from) + block + page.slice(to + END.length));
  console.log(`  ${target.page.padEnd(16)} ${summary}`);
}

if (stale) process.exit(1);
