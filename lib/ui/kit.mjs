export function kitScript() {
  return `
/*
  CMProgress — a staged progress bar.

  attach(mountSelector, steps) where each step is {label, w, slow}:
    w     relative width of the step's band (default 1)
    slow  the step eases toward its ceiling while it waits

  begin() enters step 0, next() advances, done()/fail() end it.
*/
window.CMProgress = (function () {
  function attach(mount, steps) {
    var host = typeof mount === "string" ? document.querySelector(mount) : mount;
    if (!host) return noop();

    /*
      Stop whatever was running here before.

      Two runs can overlap — a second submit while the first is still in
      flight, or the website builder's Rebuild button, which calls the same
      function again. Without this, the previous controller's interval keeps
      painting into the same element, and you get the older run's percentage
      fighting the newer run's label: a bar that reads "done" at 71%.

      Found by accident, by submitting twice. The disabled button makes it
      rare rather than impossible, and "rare" is not a fix.
    */
    if (host.__cmStop) { try { host.__cmStop(); } catch (e) {} }

    host.innerHTML =
      '<div class="prog-top">' +
        '<span class="prog-step"><span></span></span>' +
        '<span class="prog-pct"><b>0</b>%</span>' +
      '</div>' +
      '<div class="prog-track"><div class="prog-fill"></div></div>';
    host.className = "prog";
    host.setAttribute("role", "status");
    host.setAttribute("aria-live", "polite");

    var label = host.querySelector(".prog-step span");
    var pct = host.querySelector(".prog-pct b");
    var fill = host.querySelector(".prog-fill");

    var total = steps.reduce(function (a, s) { return a + (s.w || 1); }, 0);
    var bands = [], acc = 0;
    steps.forEach(function (s) {
      var from = acc / total, to = (acc + (s.w || 1)) / total;
      bands.push({ from: from, to: to, step: s });
      acc += s.w || 1;
    });

    var i = -1, timer = null, enteredAt = 0, shown = 0, dead = false;

    // Registered so the next attach() on this element can shut this one down.
    host.__cmStop = function () { dead = true; clearInterval(timer); };

    function paint(p) {
      if (dead) return;                      // superseded by a later run
      shown = Math.max(shown, p);            // never runs backwards
      fill.style.width = (shown * 100).toFixed(1) + "%";
      pct.textContent = Math.round(shown * 100);
    }

    function tick() {
      var b = bands[i];
      if (!b) return;
      var elapsed = (Date.now() - enteredAt) / 1000;
      /* Asymptotic: fast at first, then slower, never reaching the ceiling.
         tau is a guess at how long the step takes; being wrong changes the
         pace, not the honesty — the bar still stops at this step's band. */
      var tau = b.step.tau || 12;
      var eased = 1 - Math.exp(-elapsed / tau);
      paint(b.from + (b.to - b.from) * eased * 0.97);
    }

    function enter(n) {
      if (dead) return;
      i = n;
      var b = bands[i];
      if (!b) return;
      enteredAt = Date.now();
      label.textContent = b.step.label;
      host.dataset.state = "run";
      paint(b.from);
      clearInterval(timer);
      if (b.step.slow) timer = setInterval(tick, 220);
    }

    return {
      begin: function () { shown = 0; host.dataset.state = "run"; enter(0); return this; },
      next: function () { clearInterval(timer); if (i + 1 < bands.length) enter(i + 1); return this; },
      to: function (n) { clearInterval(timer); enter(Math.min(n, bands.length - 1)); return this; },
      /* The only place 100% is written. */
      done: function (msg) {
        clearInterval(timer);
        if (dead) return this;
        host.dataset.state = "done";
        label.textContent = msg || "Done";
        shown = 1; fill.style.width = "100%"; pct.textContent = "100";
        return this;
      },
      fail: function (msg) {
        clearInterval(timer);
        if (dead) return this;
        host.dataset.state = "fail";
        label.textContent = msg || "That did not work";
        return this;
      },
      reset: function () {
        clearInterval(timer);
        if (dead) return this;
        host.dataset.state = "idle";
        shown = 0; fill.style.width = "0%"; pct.textContent = "0";
        return this;
      },
    };
  }

  function noop() {
    var self = { begin: f, next: f, to: f, done: f, fail: f, reset: f };
    function f() { return self; }
    return self;
  }

  return { attach: attach };
})();
`;
}
