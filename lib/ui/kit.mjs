/*
  The shared UI kit: a progress bar and a dashboard shell.

  Eight tool pages run a request that takes between two seconds and two
  minutes. Until now every one of them did the same thing — disable the
  button, print a sentence, and leave the visitor staring at it. On the
  slower tools that reads as a page that has died.

  ── on making progress honest ──

  A progress bar that invents its own percentage is the same class of lie as
  a green "online" dot on a page where nothing runs. So this one is driven by
  real stages, and the rules are:

    · the label always names what is actually happening;
    · a stage only advances when the code actually reaches it;
    · inside a long stage the bar eases toward that stage's ceiling and
      stops there — it cannot wander into the next stage's band;
    · 100% happens on the real response and at no other time.

  The easing inside a stage is an estimate and is meant to be: it says "still
  working", which is true, and it never claims a step is finished before it
  is. What it must never do is sit at 99% for a minute, which is why each
  stage has its own ceiling rather than the whole bar having one.
*/

