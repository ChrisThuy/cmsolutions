/*
  Renders the navigation.

  ── why a <details> and not a div with a click handler ──

  The panel is a disclosure widget, and the browser already has one. <details>
  gives keyboard operation, the right roles, and — the part that matters on a
  site whose whole job is being found — a panel that opens even if the script
  never runs. The JS below adds Escape, outside-click and scroll behaviour on
  top of something that already works without it.

  ── why the links are in the HTML rather than injected ──

  Every href is real markup on every page. A crawler following the site finds
  all fourteen destinations from any one of them. A nav assembled at runtime
  is invisible to that, which for a portfolio site is the entire point lost.

  ── on the fallbacks ──

  Each page defines its own subset of custom properties: some have --serif and
  --ease-out, some only --ink and --void. Every var() here carries a literal
  fallback so the bar looks identical on all fourteen regardless.
*/

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

