function groupHtml(group, currentHref) {
  const items = pagesIn(group.key);
  if (!items.length) return "";
  const lis = items.map((p) => {
    const current = p.href === currentHref ? ' aria-current="page"' : "";
    const lead = p.lead ? ' class="sitenav-lead"' : "";
    return `          <li${lead}><a href="${p.href}"${current}>${esc(p.label)}` +
      (p.blurb ? `<span class="blurb">${esc(p.blurb)}</span>` : "") + `</a></li>`;
  }).join("\n");
  return `        <div class="sitenav-group">
          <h2>${esc(group.title)}</h2>
          <span class="note">${esc(group.note)}</span>
          <ul>
${lis}
          </ul>
        </div>`;
}

/**
 * The whole block, ready to splice into a page.
 *
 * `currentHref` marks the page you are on, in the bar and in the panel, so
 * the nav answers "where am I" as well as "where else".
 */
export function navHtml({ currentHref = null, withGap = true } = {}) {
  const groups = GROUPS.map((g) => groupHtml(g, currentHref)).filter(Boolean).join("\n");

  const bar = BAR.map((b) => {
    const cls = [b.desktopOnly ? "desktop-only" : "", b.cta ? "sitenav-cta" : ""].filter(Boolean).join(" ");
    const current = b.href === currentHref ? ' aria-current="page"' : "";
    return `      <a href="${b.href}"${cls ? ` class="${cls}"` : ""}${current}>${esc(b.label)}</a>`;
  }).join("\n");

  // The desktop-only bar links reappear inside the panel on narrow screens,
  // so nothing is only reachable at one width.
  const inPanel = BAR.filter((b) => b.desktopOnly).map((b) =>
    `        <div class="sitenav-group in-panel"><ul><li><a href="${b.href}">${esc(b.label)}</a></li></ul></div>`
  ).join("\n");

  return `${NAV_START}
<header class="sitenav" data-state="top">
  <div class="sitenav-in">
    <a class="sitenav-mark" href="/">${esc(SITE)}</a>
    <nav class="sitenav-bar" aria-label="Primary">
      <details class="sitenav-tools">
        <summary class="sitenav-toggle" aria-label="Tools and pages">Tools<span class="chev" aria-hidden="true"></span></summary>
        <div class="sitenav-panel">
${groups}
${inPanel}
        </div>
      </details>
${bar}
    </nav>
  </div>
</header>${withGap ? `\n<div class="sitenav-gap" aria-hidden="true"></div>` : ""}
${NAV_END}`;
}

/*
  Behaviour the browser does not give for free.

  Deliberately small and dependency-free: it runs on fourteen pages, four of
  which already run GSAP and a canvas, and the one thing it must never do is
  cost a frame. The scroll handler does nothing but compare two numbers, off
  a passive listener.
*/
export function navScript() {
  return `
(function () {
  var bar = document.querySelector('.sitenav');
  if (!bar) return;
  var tools = bar.querySelector('.sitenav-tools');

  /* ── show on the way up, hide on the way down ── */
  var last = window.pageYOffset || 0, ticking = false;
  function apply() {
    ticking = false;
    var y = window.pageYOffset || 0;
    if (tools && tools.open) { bar.dataset.state = 'up'; last = y; return; }
    if (y < 24) bar.dataset.state = 'top';
    else if (y > last + 6 && y > 160) bar.dataset.state = 'down';
    else if (y < last - 6) bar.dataset.state = 'up';
    last = y;
  }
  window.addEventListener('scroll', function () {
    if (!ticking) { ticking = true; requestAnimationFrame(apply); }
  }, { passive: true });
  apply();

  if (!tools) return;

  /* ── closing ──
     A disclosure that only closes by clicking its own summary is a trap on a
     phone, where the panel covers the page it is navigating. */
  function close() { tools.open = false; }

  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape' && tools.open) { close(); tools.querySelector('summary').focus(); }
  });
  document.addEventListener('click', function (e) {
    if (tools.open && !tools.contains(e.target)) close();
  });
  // Same-page anchors do not navigate, so the panel would stay over the target.
  tools.addEventListener('click', function (e) {
    if (e.target.closest('a')) close();
  });
  // A panel left open across a back-navigation restores in the wrong state.
  window.addEventListener('pageshow', function (e) { if (e.persisted) close(); });
})();
`;
}
